import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');
const databaseDir = join(repoRoot, 'packages', 'infrastructure', 'database');
const migrationsDir = join(databaseDir, 'migrations');
const outputPath = join(databaseDir, 'video-staging-bootstrap.sql');

const stagingPreludeFiles = ['video-staging-auth.sql'];
const stagingPostludeFiles = ['video-staging-data-api-lockdown.sql'];
const migrationFiles = [
  '050_video_consultations.sql',
  '051_video_interpretation_control_plane.sql',
  '052_video_interpretation_provider_expiry.sql',
  '053_video_interpretation_launch_and_self_host.sql',
  '054_video_interpretation_self_host_single_job.sql',
];

async function main() {
  const sections = await Promise.all([
    ...stagingPreludeFiles.map(async (file) => [
      `-- Video staging support: ${file}`,
      (await readFile(join(databaseDir, file), 'utf8')).trim(),
    ].join('\n')),
    ...migrationFiles.map(async (file) => [
      `-- Video staging migration: ${file}`,
      (await readFile(join(migrationsDir, file), 'utf8')).trim(),
    ].join('\n')),
  ]);

  const trackedValues = [...stagingPreludeFiles, ...migrationFiles]
    .map((file) => `  ('${file.replaceAll("'", "''")}')`)
    .join(',\n');
  const postludeSections = await Promise.all(stagingPostludeFiles.map(async (file) => [
    `-- Video staging lockdown: ${file}`,
    (await readFile(join(databaseDir, file), 'utf8')).trim(),
  ].join('\n')));
  const trackedPostludeValues = stagingPostludeFiles
    .map((file) => `  ('${file.replaceAll("'", "''")}')`)
    .join(',\n');

  const output = [
    '-- Generated by scripts/export-video-staging-bootstrap.mjs',
    '-- Video interpretation control-plane schema only; contains no business data.',
    '-- Do not hand-edit this file.',
    '',
    'CREATE EXTENSION IF NOT EXISTS pgcrypto;',
    '',
    ...sections.flatMap((section) => [section, '']),
    'CREATE TABLE IF NOT EXISTS video_interpretation_schema_migrations (',
    '  name text PRIMARY KEY,',
    '  applied_at timestamptz NOT NULL DEFAULT now()',
    ');',
    '',
    'INSERT INTO video_interpretation_schema_migrations (name)',
    'VALUES',
    trackedValues,
    'ON CONFLICT (name) DO NOTHING;',
    '',
    ...postludeSections.flatMap((section) => [section, '']),
    'INSERT INTO video_interpretation_schema_migrations (name)',
    'VALUES',
    trackedPostludeValues,
    'ON CONFLICT (name) DO NOTHING;',
    '',
  ].join('\n');

  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, output, 'utf8');
  console.log(`Wrote ${outputPath}`);
  console.log(`Included ${stagingPreludeFiles.length} staging-only support file.`);
  console.log(`Included ${migrationFiles.length} video migrations.`);
  console.log(`Included ${stagingPostludeFiles.length} staging-only lockdown file.`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
