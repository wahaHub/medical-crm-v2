import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');
const snapshotPath = join(
  repoRoot,
  'packages',
  'infrastructure',
  'database',
  'schema',
  '0000_flimsy_hairball.sql',
);
const migrationsDir = join(
  repoRoot,
  'packages',
  'infrastructure',
  'database',
  'migrations',
);
const outputPath = join(
  repoRoot,
  'packages',
  'infrastructure',
  'database',
  'full-bootstrap.sql',
);

function unwrapSnapshot(snapshotSql) {
  const start = snapshotSql.indexOf('/*');
  const end = snapshotSql.lastIndexOf('*/');

  if (start === -1 || end === -1 || end <= start) {
    throw new Error('Could not find the wrapped base schema block in 0000_flimsy_hairball.sql');
  }

  return snapshotSql.slice(start + 2, end).trim();
}

function buildMigrationTrackerSql(migrationFiles) {
  const values = migrationFiles
    .map((file) => `  ('${file.replaceAll("'", "''")}')`)
    .join(',\n');

  return [
    '-- Track the current schema head so future pnpm db:migrate runs stay incremental.',
    'CREATE TABLE IF NOT EXISTS _migrations (',
    '  id SERIAL PRIMARY KEY,',
    '  name VARCHAR(255) NOT NULL UNIQUE,',
    '  applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()',
    ');',
    '',
    'INSERT INTO _migrations (name)',
    'VALUES',
    values,
    'ON CONFLICT (name) DO NOTHING;',
  ].join('\n');
}

async function main() {
  const snapshotSql = await readFile(snapshotPath, 'utf8');
  const baseSchemaSql = unwrapSnapshot(snapshotSql);

  const migrationFiles = (await readdir(migrationsDir))
    .filter((file) => file.endsWith('.sql'))
    .sort();

  const migrationSections = await Promise.all(
    migrationFiles.map(async (file) => {
      const sql = (await readFile(join(migrationsDir, file), 'utf8')).trim();
      return [`-- Migration: ${file}`, sql].join('\n');
    }),
  );

  const output = [
    '-- Generated by scripts/export-full-bootstrap-sql.mjs',
    '-- Do not hand-edit this file. Re-run pnpm db:export:full instead.',
    '',
    '-- Fresh local PostgreSQL needs pgcrypto for gen_random_uuid().',
    'CREATE EXTENSION IF NOT EXISTS pgcrypto;',
    '',
    '-- Supabase provides auth.uid(). Plain PostgreSQL does not.',
    '-- This shim keeps local imports working without changing app behavior.',
    'CREATE SCHEMA IF NOT EXISTS auth;',
    'CREATE OR REPLACE FUNCTION auth.uid()',
    'RETURNS uuid',
    'LANGUAGE sql',
    'STABLE',
    'AS $$',
    "  SELECT NULLIF(current_setting('request.jwt.claim.sub', true), '')::uuid",
    '$$;',
    '',
    '-- Base schema snapshot from Drizzle introspection.',
    baseSchemaSql,
    '',
    '-- Follow-up migrations in the same lexical order as database/migrate.ts.',
    ...migrationSections.flatMap((section) => ['', section]),
    '',
    buildMigrationTrackerSql(migrationFiles),
    '',
  ].join('\n');

  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, output, 'utf8');

  console.log(`Wrote ${outputPath}`);
  console.log(`Included ${migrationFiles.length} migrations.`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
